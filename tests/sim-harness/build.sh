#!/bin/bash
# Build the headless simulator harness: tests/sim-harness/out/MadeiraSim.app.
#
# Links harness_main.m with the app's own Wine glue (WineServerBridge.m,
# WineProcessBridge.m, Winios, JITAllocator.c, PrefixExtractor.c, ...) and the
# unix-side archives built with MAD_SDK=iphonesimulator, then lays out the
# bundle resources the launcher reads (arm64ec-windows/, nls/, the prefix
# template). No Swift: whatever the app's Swift layer would have provided is
# found from the linker's undefined-symbol list and given a logging stub
# (out/stubs.c, listed in out/stubs.txt), so a stub that is ever reached says
# so in the log.
#
# Needs, built for the simulator: app/Madeira/libntdll_unix.a, libwineserver.a,
# libwin32u_unix.a, the FFmpeg archives in app/Madeira, toolchains/gnutls-ios.
set -euo pipefail

H="$(cd "$(dirname "$0")" && pwd)"
R="$(cd "$H/../.." && pwd)"
A="$R/app/Madeira"
OUT="$H/out"
OBJ="$OUT/obj"
APP="$OUT/MadeiraSim.app"
SDK=$(xcrun --sdk iphonesimulator --show-sdk-path)
TARGET=arm64-apple-ios17.0-simulator
CC=(xcrun -sdk iphonesimulator clang -target "$TARGET" -isysroot "$SDK")

rm -rf "$OBJ" && mkdir -p "$OBJ"

CFLAGS=(-O1 -g -fno-stack-protector -Wno-deprecated-declarations
        -Wno-implicit-function-declaration -Wno-int-conversion
        -I"$A" -I"$A/Winios" -I"$R/build")
OBJCFLAGS=(-fobjc-arc -fmodules)

SOURCES=(
    "$H/harness_main.m"
    "$H/harness_glue.c"
    "$H/txm_shim.c"
    "$A/WineServerBridge.m"
    "$A/WineProcessBridge.m"
    "$A/JITAllocator.c"
    "$A/PrefixExtractor.c"
    "$A/wine_stubs.c"
    "$A/IOSDisplayShim.m"
    "$A/PadOutput.m"
    "$A/Winios/Winios.m"
    "$A/Winios/WiniosCursor.c"
    "$A/Winios/WiniosGamepad.c"
)

echo "=== compiling the harness and the app's Wine glue ($TARGET) ==="
FAILED=0
for src in "${SOURCES[@]}"; do
    name=$(basename "$src"); name="${name%.*}"
    extra=()
    case "$src" in *.m) extra=("${OBJCFLAGS[@]}") ;; esac
    if "${CC[@]}" "${CFLAGS[@]}" ${extra[@]+"${extra[@]}"} -c "$src" -o "$OBJ/$name.o" 2>"$OBJ/$name.err"; then
        echo "  $name OK"
    else
        echo "  $name FAILED"; grep -m 20 -B 2 -A 3 'error:' "$OBJ/$name.err" || head -40 "$OBJ/$name.err"
        FAILED=1
    fi
done
[ $FAILED = 0 ] || exit 1

# Frameworks the app target links, where the simulator SDK has them.
FW=()
for f in Foundation UIKit CoreFoundation Metal MetalFX QuartzCore AVFoundation AudioToolbox \
         CoreMedia CoreVideo VideoToolbox ImageIO IOKit GameController CoreHaptics \
         CoreGraphics Security SystemConfiguration Network; do
    [ -d "$SDK/System/Library/Frameworks/$f.framework" ] && FW+=(-framework "$f")
done
GNUTLS="$R/toolchains/gnutls-ios/lib"
# A private copy of libwineserver.a: duplicates between it and ntdll's unix side
# are renamed in it (below), never in the archive the app links.
WSLIB="$OUT/libwineserver.a"
cp "$A/libwineserver.a" "$WSLIB"
LIBS=("$A/libntdll_unix.a" "$WSLIB" "$A/libwin32u_unix.a"
      "$A/libavformat.a" "$A/libavcodec.a" "$A/libswresample.a" "$A/libavutil.a"
      "$GNUTLS/libgnutls.a" "$GNUTLS/libhogweed.a" "$GNUTLS/libnettle.a" "$GNUTLS/libgmp.a"
      -lc++ -lz -lsqlite3 -llzma -lresolv -liconv)
for l in "${LIBS[@]}"; do
    case "$l" in -*) ;; *) [ -f "$l" ] || { echo "missing $l"; exit 1; } ;; esac
done
OBJCOPY=$(command -v llvm-objcopy || echo "$R/toolchains/llvm-mingw-20260421-ucrt-macos-universal/bin/llvm-objcopy")

link() {
    "${CC[@]}" -o "$APP/madeira-sim" "$OBJ"/*.o "${LIBS[@]}" "${FW[@]}" \
        -Wl,-rpath,@executable_path/Frameworks 2>"$OUT/link.err"
}

write_stubs() {
    {
        echo '/* Generated by tests/sim-harness/build.sh: symbols only the app'"'"'s Swift layer'
        echo ' * or a library the harness does not link (DXMT) defines. A function logs when'
        echo ' * reached; a unix-call table is an empty one. */'
        echo '#include <stdio.h>'
        i=0
        while read -r sym; do
            case "$sym" in
                *_unix_call_funcs|*_unix_call_wow64_funcs)
                    echo "const void *sim_stub_$i[512] __asm__(\"$sym\") = { 0 };" ;;
                *)
                    echo "long sim_stub_$i(void) __asm__(\"$sym\");"
                    echo "long sim_stub_$i(void) { fprintf(stderr, \"[sim-stub] %s called\n\", \"$sym\"); return 0; }" ;;
            esac
            i=$((i + 1))
        done < "$OUT/stubs.txt"
    } > "$OUT/stubs.c"
    "${CC[@]}" -O1 -c "$OUT/stubs.c" -o "$OBJ/zz_stubs.o"
}

# The wineserver runs in-process, so a global that both it and ntdll's unix side
# define is two programs' state under one name; build/wineserver/build.sh renames
# the known ones (shared_session, user_shared_data) to ws_*. Same here, for any
# the link reports, in the copy only.
rename_ws() {
    local d="$OUT/ws-rename" args=()
    while read -r sym; do args+=(--redefine-sym "$sym=_ws_${sym#_}"); done < "$OUT/renamed.txt"
    rm -rf "$d" && mkdir -p "$d"
    (cd "$d" && ar x "$A/libwineserver.a")
    for f in "$d"/*.o; do "$OBJCOPY" "${args[@]}" "$f"; done
    rm -f "$WSLIB" && ar rcs "$WSLIB" "$d"/*.o && rm -rf "$d"
}

rm -rf "$APP" && mkdir -p "$APP"
: > "$OUT/stubs.txt"; : > "$OUT/renamed.txt"
for pass in 1 2 3 4 5; do
    echo "=== link (pass $pass) ==="
    if link; then echo "  linked"; break; fi
    progress=0
    # ld64: '  "_symbol", referenced from:'
    sed -n 's/^  "\(.*\)", referenced from:$/\1/p' "$OUT/link.err" | sort -u > "$OUT/undef.txt"
    if [ -s "$OUT/undef.txt" ]; then
        if grep -q 'OBJC_CLASS_\|OBJC_METACLASS_' "$OUT/undef.txt"; then
            echo "  an Objective-C class is undefined; it cannot be stubbed:"; grep OBJC_ "$OUT/undef.txt"; exit 1
        fi
        echo "  undefined -> stubs:"; sed 's/^/    /' "$OUT/undef.txt"
        sort -u "$OUT/stubs.txt" "$OUT/undef.txt" -o "$OUT/stubs.txt"
        write_stubs; progress=1
    fi
    # ld64: "duplicate symbol '_x' in:" then the two members, one per line
    awk "/^duplicate symbol '/ { s=\$3; gsub(/'/, \"\", s); getline a; getline b;
         if ((a ~ /libwineserver/) || (b ~ /libwineserver/)) print s }" "$OUT/link.err" | sort -u > "$OUT/dup.txt"
    if [ -s "$OUT/dup.txt" ]; then
        echo "  defined by both ntdll's unix side and the wineserver -> ws_* in the server's copy:"
        sed 's/^/    /' "$OUT/dup.txt"
        sort -u "$OUT/renamed.txt" "$OUT/dup.txt" -o "$OUT/renamed.txt"
        rename_ws; progress=1
    fi
    [ $progress = 1 ] || { cat "$OUT/link.err"; exit 1; }
done
[ -x "$APP/madeira-sim" ] || { echo "link did not converge"; cat "$OUT/link.err"; exit 1; }
grep -i 'warning' "$OUT/link.err" | grep -v 'was built for newer' | head -5 || true

echo "=== bundle ==="
cat > "$APP/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleExecutable</key><string>madeira-sim</string>
    <key>CFBundleIdentifier</key><string>dev.madeira.simharness</string>
    <key>CFBundleName</key><string>MadeiraSim</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleVersion</key><string>1</string>
    <key>CFBundleShortVersionString</key><string>1.0</string>
    <key>MinimumOSVersion</key><string>17.0</string>
    <key>CFBundleSupportedPlatforms</key><array><string>iPhoneSimulator</string></array>
    <key>UIDeviceFamily</key><array><integer>1</integer><integer>2</integer></array>
</dict>
</plist>
PLIST
for r in arm64ec-windows aarch64-windows i386-windows nls x86_64-vcruntime; do
    [ -d "$A/$r" ] && cp -R "$A/$r" "$APP/$r"
done
for r in prefix-template.tar.gz cacert.pem; do cp "$A/$r" "$APP/$r"; done
# Upper-case aliases (GDI32.dll -> gdi32.dll): a DLL that names its imports in upper case
# (the game, DXMT's dxgi.dll) misses them in this bundle, which sits on a case-sensitive
# volume, where Wine's fallback opens <bundle>/arm64ec-windows/<name as written>.
( cd "$APP/arm64ec-windows" && for f in *.dll; do
    u="$(printf '%s' "${f%.dll}" | tr '[:lower:]' '[:upper:]').dll"
    [ -e "$u" ] || ln -s "$f" "$u"
  done )
echo "upper-case DLL aliases: $(find "$APP/arm64ec-windows" -maxdepth 1 -type l -name '*.dll' | wc -l)"
codesign -f -s - "$APP/madeira-sim"
codesign -f -s - "$APP" 2>/dev/null || true
xcrun vtool -show-build "$APP/madeira-sim" | grep -E 'platform|minos|sdk' || true
du -sh "$APP"
echo "Done: $APP"
